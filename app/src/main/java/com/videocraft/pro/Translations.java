    private static void add(String ar, String en, String fr) {
        map.put(ar, new String[]{ar, en, fr});
    }

    public static String tr(int lang, String ar) {
        String[] v = map.get(ar);
        if (v == null) return ar;
        if (lang < 0 || lang > 2) return ar;
        return v[lang];
    }

    public static String getLangName(int lang) {
        switch (lang) {
            case LANG_EN: return "English";
            case LANG_FR: return "Français";
            default: return "العربية";
        }
    }
